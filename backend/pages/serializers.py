class PageListSerializer(serializers.ModelSerializer):
    block_count = serializers.SerializerMethodField()
    owner_name = serializers.CharField(source='owner.username', read_only=True, default='')
    is_shared = serializers.SerializerMethodField()
    preview_blocks = serializers.SerializerMethodField()

    class Meta:
        model = Page
        fields = [
            'id', 'name', 'slug', 'status', 'design_tokens',
            'seo_title', 'seo_description', 'seo_canonical_url',
            'og_title', 'og_description', 'og_image', 'og_type', 'noindex', 'language',
            'block_count', 'owner_name', 'is_shared', 'preview_blocks',
            'published_at', 'has_unpublished_changes', 'version',
            'created_at', 'updated_at',
        ]
        # status only changes through the publish/unpublish actions
        read_only_fields = [
            'id', 'slug', 'status', 'published_at', 'has_unpublished_changes', 'version',
            'created_at', 'updated_at',
        ]

    def get_block_count(self, obj):
        # The list view annotates the total because it prefetches only the preview blocks
        total = getattr(obj, 'block_total', None)
        return total if total is not None else obj.blocks.count()

    def get_is_shared(self, obj):
        request = self.context.get('request')
        if request and request.user:
            return obj.owner_id != request.user.pk
        return False

    def get_preview_blocks(self, obj):
        # The list view prefetches only the first blocks, into `preview_blocks_cache`
        blocks = getattr(obj, PREVIEW_BLOCKS_ATTR, None)
        if blocks is None:
            blocks = obj.blocks.order_by('order')[:LIST_PREVIEW_BLOCKS]
        return PreviewBlockSerializer(blocks, many=True).data


class PageDetailSerializer(serializers.ModelSerializer):
    blocks = BlockSerializer(many=True)
    # Whether the requesting user owns the page: collaborators cannot publish,
    # duplicate, delete versions or regenerate it with AI (ADR-032)
    is_owner = serializers.SerializerMethodField()
    # Not the model's URLField validator, which refuses a site path such as an
    # uploaded "/media/assets/..." (SEC2-006): validate_og_image is the rule
    og_image = serializers.CharField(max_length=500, required=False, allow_blank=True, trim_whitespace=False)

    def get_is_owner(self, obj):
        request = self.context.get('request')
        user = getattr(request, 'user', None)
        return bool(user is not None and user.is_authenticated and is_page_owner(obj, user))

    def validate_design_tokens(self, value):
        return clean_design_tokens(value)

    def validate_og_image(self, value):
        return validate_safe_image_url(value)

    def validate_blocks(self, blocks):
        """At most MAX_BLOCKS_PER_PAGE; client-generated ids must be unique and must not belong to another page."""
        if len(blocks) > MAX_BLOCKS_PER_PAGE:
            raise serializers.ValidationError(f'Máximo {MAX_BLOCKS_PER_PAGE} bloques por página.')
        ids = [str(b['id']) for b in blocks if b.get('id')]
        if len(ids) != len(set(ids)):
            raise serializers.ValidationError('Hay bloques con el mismo id.')

        foreign = Block.objects.filter(id__in=ids)
        if self.instance is not None:
            foreign = foreign.exclude(page=self.instance)
        if foreign.exists():
            raise serializers.ValidationError('Algún id de bloque ya está en uso.')
        return blocks

    class Meta:
        model = Page
        fields = [
            'id', 'name', 'slug', 'status', 'design_tokens',
            'seo_title', 'seo_description', 'seo_canonical_url',
            'og_title', 'og_description', 'og_image', 'og_type', 'noindex', 'language',
            'blocks', 'published_at', 'has_unpublished_changes', 'version', 'is_owner',
            'created_at', 'updated_at',
        ]
        # status only changes through the publish/unpublish actions, so an
        # autosave can never publish or unpublish a page. The version is
        # checked and bumped by PageViewSet.update (pages/sync.py), never
        # taken from the payload.
        read_only_fields = [
            'id', 'slug', 'status', 'published_at', 'has_unpublished_changes', 'version', 'is_owner',
            'created_at', 'updated_at',
        ]

    def create(self, validated_data):
        blocks_data = validated_data.pop('blocks', [])
        page = Page.objects.create(**validated_data)
        for i, block_data in enumerate(blocks_data):
            block_data.setdefault('order', i)
            # Keeps the client-generated id when present (validated in validate_blocks)
            Block.objects.create(page=page, **block_data)
        return page

    def update(self, instance, validated_data):
        with transaction.atomic():
            blocks_data = validated_data.pop('blocks', None)

            # Update page fields
            for attr, value in validated_data.items():
                setattr(instance, attr, value)
            instance.save()

            # If blocks were provided, replace them all (full sync from frontend)
            if blocks_data is not None:
                # Convert to strings for reliable comparison (UUID vs str mismatch)
                existing_ids = {str(uid) for uid in instance.blocks.values_list('id', flat=True)}
                incoming_ids = set()

                for i, block_data in enumerate(blocks_data):
                    block_data.setdefault('order', i)
                    block_id = str(block_data.get('id', '')) if block_data.get('id') else ''

                    if block_id and block_id in existing_ids:
                        # Update existing block. data is replaced, not merged: a
                        # key the editor removed must really go (ADR-024). A stale
                        # payload can no longer drop keys it did not know about
                        # because it is refused with 409 before it gets here.
                        block = instance.blocks.get(id=block_id)
                        for attr, value in block_data.items():
                            if attr != 'id':
                                setattr(block, attr, value)
                        block.save()
                        incoming_ids.add(block_id)
                    else:
                        # New block: keeps the client-generated id when present
                        new_block = Block.objects.create(page=instance, **block_data)
                        incoming_ids.add(str(new_block.id))

                # Delete blocks that were removed
                blocks_to_delete = existing_ids - incoming_ids
                if blocks_to_delete:
                    instance.blocks.filter(id__in=blocks_to_delete).delete()

                # Clear prefetch cache so the response reflects current blocks
                if hasattr(instance, '_prefetched_objects_cache'):
                    instance._prefetched_objects_cache.pop('blocks', None)

            return instance


