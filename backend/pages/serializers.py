# A page is a handful of landing sections: more than this is a mistake or abuse
# (2,200 blocks made a 7.8 MB public page)
MAX_BLOCKS_PER_PAGE = 100
# Blocks the dashboard card previews
LIST_PREVIEW_BLOCKS = 4
PREVIEW_BLOCKS_ATTR = 'preview_blocks_cache'


class AssetSerializer(serializers.ModelSerializer):
    url = serializers.SerializerMethodField()

    class Meta:
        model = Asset
        fields = ['id', 'name', 'file', 'url', 'mime_type', 'size', 'created_at']
        read_only_fields = ['id', 'name', 'url', 'mime_type', 'size', 'created_at']
        extra_kwargs = {'file': {'write_only': True}}

    def get_url(self, obj):
        # Relative to the site ("/media/assets/..."), not to the API host: the
        # URL is stored in pages, which must not depend on where the API runs.
        # The frontend forwards /media to the backend like it does /api.
        return obj.file.url if obj.file else ''


class BlockSerializer(serializers.ModelSerializer):
    # Block ids are generated by the client (UUID v4) so a block keeps the
    # same id before and after it is saved (ADR-014).
    id = serializers.UUIDField(required=False)

    class Meta:
        model = Block
        fields = ['id', 'type', 'order', 'data', 'styles', 'created_at', 'updated_at']
        read_only_fields = ['created_at', 'updated_at']

    def validate_styles(self, value):
        # Same rule as the WebSocket path (SEC2-007): any JSON used to be stored as is
        return clean_block_styles(value)

    def validate(self, attrs):
        attrs = super().validate(attrs)
        initial_data = getattr(self, 'initial_data', {}) or {}
        block_type = attrs.get('type') or initial_data.get('type')
        if block_type is None and self.instance is not None:
            block_type = self.instance.type

        try:
            if block_type not in BLOCK_VALIDATORS:
                raise serializers.ValidationError(f'Tipo de bloque desconocido: {block_type}.')
            if attrs.get('data') is not None:
                attrs['data'] = clean_block_data(block_type, attrs['data'], partial=self._is_partial_block_update())
        except serializers.ValidationError as exc:
            field = 'type' if block_type not in BLOCK_VALIDATORS else 'data'
            raise serializers.ValidationError({field: exc.detail})
        return attrs

    def _is_partial_block_update(self):
        initial_data = getattr(self, 'initial_data', {}) or {}
        block_id = initial_data.get('id')
        return bool(block_id) and isinstance(block_id, str) and not block_id.startswith('blk_')


